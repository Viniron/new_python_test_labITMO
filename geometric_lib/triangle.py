def area(a, h):
    '''
    Считает площадь треугольника по стороне и высоте, проведённой к ней.

    Параметры:
        a (float): длина стороны треугольника
        h (float): длина высоты, опущенной на сторону a

    Возвращаемое значение:
        float: площадь треугольника

    Пример вызова:
        area(6, 4)  # 12.0
    '''
    return a * h / 2


def perimeter(a, b, c):
    '''
    Считает периметр треугольника по трём его сторонам.

    Параметры:
        a (float): длина первой стороны
        b (float): длина второй стороны
        c (float): длина третьей стороны

    Возвращаемое значение:
        float: периметр треугольника

    Пример вызова:
        perimeter(3, 4, 5)  # 12
    '''
    return a + b + c
